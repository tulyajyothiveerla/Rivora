CREATE TABLE IF NOT EXISTS "PlatformSetting" (
  "key" VARCHAR(80) PRIMARY KEY,
  "value" JSONB NOT NULL,
  "updatedBy" UUID REFERENCES "AppUser"("id") ON DELETE SET NULL,
  "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "StaffPermission" (
  "userId" UUID NOT NULL REFERENCES "AppUser"("id") ON DELETE CASCADE,
  "scope" VARCHAR(32) NOT NULL
    CHECK ("scope" IN (
      'OPERATIONS','CUSTOMERS','TEAM_MANAGEMENT','COMMUNITIES','SUPPORT',
      'FINANCE','MARKETPLACE','MODERATION','REPORTS','AUDIT'
    )),
  "grantedBy" UUID NOT NULL REFERENCES "AppUser"("id"),
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("userId","scope")
);
